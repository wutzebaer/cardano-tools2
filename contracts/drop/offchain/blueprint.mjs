// Writes app/cardano/dropBlueprint.ts from plutus.json: the compiled contract and where its term ends.
//
// The flat encoding does not say where the term ends and its filler begins, and the site appends the parameters
// right there. So every possible end is tried until the script equals the one a full implementation produces.
//
//   aiken build && node blueprint.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { Constr, applyDoubleCborEncoding, applyParamsToScript, mintingPolicyToId } from "@lucid-evolution/lucid";
import { applyDropParams, scriptHash } from "../../../app/cardano/dropScript.ts";

const blueprint = JSON.parse(readFileSync(new URL("../plutus.json", import.meta.url), "utf8"));
const validator = blueprint.validators.find((entry) => entry.title === "drop.drop.spend");
const compiled = Buffer.from(validator.compiledCode, "hex");
// the compiled code is a CBOR byte string around the flat bytes
const header = compiled[0] === 0x59 ? 3 : compiled[0] === 0x58 ? 2 : 1;
const code = compiled.subarray(header).toString("hex");

const samples = [
  { seed: { txHash: "ab".repeat(32), index: 0 }, burnable: false },
  { seed: { txHash: "0123456789abcdef".repeat(4), index: 7 }, burnable: true },
];
const expected = (sample) =>
  mintingPolicyToId({
    type: "PlutusV3",
    script: applyParamsToScript(applyDoubleCborEncoding(validator.compiledCode), [
      new Constr(0, [sample.seed.txHash, BigInt(sample.seed.index)]),
      new Constr(sample.burnable ? 1 : 0, []),
    ]),
  });

const allBits = (code.length / 2 - 3) * 8;
const fits = [];
for (let termBits = allBits - 8; termBits < allBits; termBits++) {
  if (samples.every((sample) => scriptHash(applyDropParams(code, termBits, sample.seed, sample.burnable)) === expected(sample))) fits.push(termBits);
}
if (fits.length !== 1) throw new Error(`expected one end of the term, found ${fits.length}`);

writeFileSync(
  new URL("../../../app/cardano/dropBlueprint.ts", import.meta.url),
  `// Generated by contracts/drop/offchain/blueprint.mjs from the compiled contract, do not edit.

/** Hash of the contract before its parameters are applied, to tell which build this is. */
export const DROP_BLUEPRINT_HASH = "${validator.hash}";

/** Number of bits of the contract's term, the parameters are appended after them. */
export const DROP_TERM_BITS = ${fits[0]};

/** The compiled contract in the flat encoding, as hex. */
export const DROP_CODE =
  "${code}";
`,
);
console.log(`blueprint ${validator.hash}: ${code.length / 2} bytes, term of ${fits[0]} bits`);
