import { components } from "@cardano/dbsync.schema";

export type Cardano = Map<string, WalletInfo>;

export interface WalletInfo {
  apiVersion: string;
  name: string;
  icon: string;
  isEnabled: () => Promise<boolean>;
  enable: () => Promise<WalletConnection>;
}

export interface WalletConnection {
  getBalance: () => Promise<string>;
  getChangeAddress: () => Promise<string>;
  getRewardAddresses: () => Promise<string[]>;
  getNetworkId: () => Promise<number>;
  getUtxos: () => Promise<string[] | null | undefined>;
  getUsedAddresses: () => Promise<string[]>;
  getUnusedAddresses: () => Promise<string[]>;
  getCollateral: () => Promise<string[]>;
  signTx: (cbor: string, partialSign: boolean) => Promise<string>;
  submitTx: (cbor: string) => Promise<string>;
}

export interface SimpleScript {
  type: "all" | "any" | "atLeast" | "before" | "after" | "sig";
  scripts?: SimpleScript[];
  required?: number;
  slot?: number;
  keyHash?: string;
}

/** Native script JSON (sig / all / before). Only on-chain after the first mint. */
export interface MintPolicy {
  policyId: string;
  script: SimpleScript;
  /** Label for policies kept in this browser. */
  name?: string;
  /**
   * Hex of the ed25519 signing key, only for policies imported from the old Cardano Tools
   * (their key was generated by the server). Stays in this browser's local storage.
   */
  skey?: string;
}

/** CIP-68 user token class: 222 = NFT, 333 = FT */
export type TokenStandard = 222 | 333;

export interface TokenProperty {
  key: string;
  value: string;
}

export interface MintToken {
  id: string;
  standard: TokenStandard;
  assetName: string;
  amount: string;
  name: string;
  description: string;
  /** image (222) or logo (333) URI: ipfs://, https://, ar:// or data: */
  image: string;
  mediaType: string;
  ticker: string;
  url: string;
  decimals: string;
  properties: TokenProperty[];
}

export type TokenListItem = components["schemas"]["TokenListItem"];
export type TokenDetails = components["schemas"]["TokenDetails"];
export type StakeInfo = components["schemas"]["StakeInfo"];
